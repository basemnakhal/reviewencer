import { Sparkles, ThumbsUp, ThumbsDown } from 'lucide-react';
import type { AiSummary as AiSummaryType } from '@/lib/types';
import { cn } from '@/lib/utils';

interface Props { summary: AiSummaryType; businessName: string }

export function AiSummary({ summary, businessName }: Props) {
  const sentiment = summary.sentiment ?? 50;
  return (
    <section className="overflow-hidden rounded-3xl border border-royal-200 bg-white">
      <header className="flex items-center gap-2 bg-brand-gradient px-5 py-3 text-white">
        <Sparkles size={16} />
        <span className="text-[11px] font-black uppercase tracking-[0.15em]">
          AI summary · {summary.review_count} reviews
        </span>
      </header>

      <div className="p-5">
        <p className="text-lg font-black leading-snug text-royal-900">{summary.headline}</p>

        {summary.themes.length > 0 && (
          <div className="mt-4 grid grid-cols-2 gap-2 sm:grid-cols-3">
            {summary.themes.map((t) => (
              <ThemeChip key={t.label} label={t.label} score={t.score} />
            ))}
          </div>
        )}

        <div className="mt-5 grid gap-4 sm:grid-cols-2">
          <div className="rounded-xl border border-stone-200 bg-cream-50/60 p-4">
            <div className="mb-2 flex items-center gap-1.5 text-xs font-black uppercase tracking-wider text-royal-700">
              <ThumbsUp size={12} /> People love
            </div>
            <ul className="space-y-1 text-sm text-royal-900/90">
              {summary.pros.map((p) => <li key={p}>• {p}</li>)}
            </ul>
          </div>

          <div className="rounded-xl border border-stone-200 bg-cream-50/60 p-4">
            <div className="mb-2 flex items-center gap-1.5 text-xs font-black uppercase tracking-wider text-gold-700">
              <ThumbsDown size={12} /> Watch out for
            </div>
            <ul className="space-y-1 text-sm text-royal-900/90">
              {summary.cons.map((p) => <li key={p}>• {p}</li>)}
            </ul>
          </div>
        </div>

        <SentimentBar value={sentiment} />

        <p className="mt-4 text-[11px] italic text-stone-500">
          Generated by {summary.generated_by ?? 'AI'} · stale summaries refresh when new reviews land.
          {' '}Every quoted claim is backed by a real {businessName} review.
        </p>
      </div>
    </section>
  );
}

function ThemeChip({ label, score }: { label: string; score: number }) {
  const good = score >= 60;
  return (
    <div className={cn(
      'rounded-lg border px-2.5 py-1.5 text-xs',
      good ? 'border-royal-200 bg-royal-50 text-royal-900' : 'border-gold-200 bg-gold-50 text-gold-900',
    )}>
      <div className="font-bold">{label}</div>
      <div className="tabular-nums text-[10px] opacity-70">{score}/100</div>
    </div>
  );
}

function SentimentBar({ value }: { value: number }) {
  return (
    <div className="mt-5">
      <div className="mb-1 flex items-center justify-between text-[11px] font-bold text-stone-500">
        <span>Overall sentiment</span>
        <span className="tabular-nums text-royal-900">{value}/100</span>
      </div>
      <div className="h-2 w-full overflow-hidden rounded-full bg-stone-100">
        <div className="h-full bg-brand-gradient transition-all" style={{ width: `${value}%` }} />
      </div>
    </div>
  );
}
